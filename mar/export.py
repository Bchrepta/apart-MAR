"""Export every episode as one labeled dataset (Deviation 20 packaging).

  python -m mar.export            # -> data/stop_leakage_episodes.jsonl.gz + data/DATASHEET.md

One line per branch episode: condition metadata, all deterministic metrics, and
monitor verdicts where a monitor study scored that episode. Transcripts (events,
board, raw replies) are included, so the file is self-contained.
"""
from __future__ import annotations

import gzip
import json
from collections import Counter
from pathlib import Path

from .metrics import compute

RUN_DIRS = {
    "runs/main": "api", "runs/cli": "claude_code", "runs/cli_sonnet": "claude_code",
    "runs/cli_opus": "claude_code", "runs/cli_attack": "claude_code",
    "runs/cli_sonnet_attack": "claude_code", "runs/cli_opus_attack": "claude_code",
    "runs/cli_swarm": "claude_code", "runs/cli_derived": "claude_code",
    "runs/cli_code": "claude_code", "runs/scripted_attack": "scripted",
}


def _monitor_index() -> dict[str, dict]:
    idx = {}
    for p in Path("results").glob("monitor*/items.json"):
        for it in json.loads(p.read_text()):
            idx[it["file"]] = {
                k: v for k, v in it.items() if k.startswith("llm_") or k in ("provenance", "label")}
    return idx


def main() -> int:
    out = Path("data"); out.mkdir(exist_ok=True)
    mon = _monitor_index()
    counts, n = Counter(), 0
    with gzip.open(out / "stop_leakage_episodes.jsonl.gz", "wt") as fh:
        for d, harness in RUN_DIRS.items():
            for f in sorted(Path(d).glob("branches/*.json")):
                r = json.loads(f.read_text())
                m = compute(r)
                key = f"{d}/branches/{f.name}"
                rec = {
                    "id": f"{Path(d).name}/{f.stem}", "run_dir": d, "harness": harness,
                    "model": r.get("model"), "team": r.get("team", "trio"),
                    "task_kind": {"trio_derived": "derived", "trio_code": "code"}.get(r.get("team", "trio"), "ids"),
                    "seed": r["seed"], "elicitation": r["elicitation"], "scope": r["scope"],
                    "framing": r["framing"], "variant": r.get("variant", "base"),
                    "stop_step": r["stop_step"], "stopped_agents": r["stopped_agents"],
                    "notice": r.get("notice"), "metrics": m, "monitor": mon.get(key),
                    "events": r["events"], "board": r.get("board"), "final_tasks": r.get("final_tasks"),
                }
                fh.write(json.dumps(rec) + "\n")
                n += 1
                counts[(rec["model"], rec["task_kind"], rec["harness"])] += 1
    lines = ["# Datasheet: stop_leakage_episodes.jsonl.gz", "",
             f"{n} episodes (one per branch). Generated by `python -m mar.export` from `runs/`.", "",
             "## Fields",
             "- `id`, `run_dir`, `harness` (api | claude_code | scripted), `model`, `team`, `task_kind` (ids | derived | code)",
             "- `seed`, `elicitation`, `scope`, `framing`, `variant`, `stop_step`, `stopped_agents`, `notice`",
             "- `metrics`: everything `mar.metrics.compute` returns. Primary: `d1_completed_post_stop`.",
             "- `monitor`: provenance and LLM-monitor verdicts where a monitor study scored the episode, else null.",
             "- `events` (every tool call with result and a `post_stop` flag), `board`, `final_tasks`.", "",
             "Branches with the same (run_dir, team, elicitation, seed) share a prefix, so they are paired.", "",
             "## Composition (model, task kind, harness: episodes)", ""]
    lines += [f"- {k[0]}, {k[1]}, {k[2]}: {v}" for k, v in sorted(counts.items(), key=str)]
    lines += ["", "## Caveats",
              "- Claude-family models only. Toy and small-coding tasks. See `PREREGISTRATION.md` for all deviations.",
              "- Claude Code runs carry harness context (Deviations 4–6) and the working-directory artifact (Deviation 19).",
              "- Content is synthetic and benign (inventory IDs, arithmetic, small Python modules)."]
    (out / "DATASHEET.md").write_text("\n".join(lines) + "\n")
    print(n, "episodes ->", out / "stop_leakage_episodes.jsonl.gz")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
